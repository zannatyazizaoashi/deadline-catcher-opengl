def start_rain(now_ms):
    global rain_active, rain_end_ms, rain_wind_x, rain_wind_y
    rain_active = True
    rain_end_ms = now_ms + rain_duration_ms
    ax = rand01() * 2.0 - 1.0
    ay = rand01() * 2.0 - 1.0
    m = (ax * ax + ay * ay) ** 0.5
    if m < 0.001:
        ax, ay = 1.0, 0.0
        m = 1.0
    ax /= m
    ay /= m
    rain_wind_x = ax * (80.0 + 140.0 * rand01())
    rain_wind_y = ay * (40.0 + 140.0 * rand01())

def ensure_screen_drop():
    if len(rain_drops) >= rain_max_drops:
        return
    x = 1000.0 * rand01()
    y = 800.0 * rand01()
    rain_drops.append([x, y])

def update_rain(dt, now_ms):
    global rain_active, rain_next_start_ms
    if game_state != state_playing:
        rain_active = False
        rain_drops[:] = []
        rain_next_start_ms = 0
        return
    if rain_next_start_ms == 0:
        rain_next_start_ms = now_ms + rain_interval_ms
    if (not rain_active) and now_ms >= rain_next_start_ms:
        start_rain(now_ms)
        rain_next_start_ms = now_ms + rain_interval_ms
    if rain_active and now_ms >= rain_end_ms:
        rain_active = False
        rain_drops[:] = []
        return
    if not rain_active:
        return
    target = int(280 + 180 * night_factor())
    if target > rain_max_drops:
        target = rain_max_drops
    while len(rain_drops) < target:
        ensure_screen_drop()
    vx = rain_wind_x
    vy = rain_wind_y
    fall = 980.0
    for d in rain_drops:
        d[0] += vx * dt
        d[1] -= fall * dt
        d[1] += (-vy) * dt
        if d[1] < -30.0 or d[0] < -60.0 or d[0] > 1060.0:
            d[0] = 1000.0 * rand01()
            d[1] = 820.0 + 200.0 * rand01()

def update(dt, now_ms):
    global player_y, score
    global jumping, jump_t, sliding, slide_t
    global active_power, power_t
    global collapsed_lane, collapse_t
    global player_ground_z
    global jetpack_active, jetpack_landing
    global hoverboard_grace_t, hoverboard_active, hoverboard_t
    global play_cycle_elapsed

    if game_over:
        return

    play_cycle_elapsed += dt

    player_y += player_speed * dt
    score = player_y * 0.05
    update_hoverboard_award()

    if hoverboard_grace_t > 0.0:
        hoverboard_grace_t -= dt
        if hoverboard_grace_t < 0.0:
            hoverboard_grace_t = 0.0

    if hoverboard_active:
        hoverboard_t -= dt
        if hoverboard_t <= 0.0:
            hoverboard_active = False
            hoverboard_t = 0.0

    if jumping:
        jump_t += dt
        if jump_t >= jump_time:
            jumping = False
            jump_t = 0.0

    if sliding:
        slide_t += dt
        if slide_t >= slide_time:
            sliding = False
            slide_t = 0.0

    if is_sneakers() and jumping and (not (is_jetpack() or jetpack_active)):
        top = train_top_under_player()
        if top is not None:
            if jump_t >= (jump_time * 0.55):
                feet = player_bottom_z()
                train_surface = top + player_base_z_default
                if feet <= train_surface + 14.0:
                    jumping = False
                    jump_t = 0.0
                    player_ground_z = train_surface

    if power_t > 0.0:
        power_t -= dt
        if power_t <= 0.0:
            power_t = 0.0
            if active_power == pow_lane_collapse:
                collapsed_lane = None
                collapse_t = 0.0
            if active_power == pow_jetpack:
                jetpack_active = False
                jetpack_landing = True
            active_power = None

    if collapse_t > 0.0:
        collapse_t -= dt
        if collapse_t <= 0.0:
            collapse_t = 0.0

    spawn_until(player_y + spawn_ahead)
    ensure_pickup_exists_ahead()

    cut = player_y - 2600.0
    obstacles[:] = [o for o in obstacles if (o["y"] > cut) and (not o["meta"].get("gone", False))]

    target_ground = player_base_z_default

    if is_jetpack() or jetpack_active:
        target_ground = 300.0
        jumping = False
        jump_t = 0.0
        sliding = False
        slide_t = 0.0
    else:
        if is_sneakers() and (not jumping):
            top = train_top_under_player()
            if top is not None:
                target_ground = top + player_base_z_default
        if jetpack_landing:
            target_ground = player_base_z_default
            if abs(player_ground_z - target_ground) < 1.5:
                jetpack_landing = False

    player_ground_z = smooth_to(player_ground_z, target_ground, dt, speed=7.5)

    collision_check()
    update_rain(dt, now_ms)

