def collision_check():
    global game_over
    if lane_is_collapsed(player_lane):
        game_over = True
        return
    if is_jetpack():
        return
    if hoverboard_grace_t > 0.0:
        return
    invincible = is_invincible()
    sneakers = is_sneakers()
    sneakers_jump_immunity = sneakers and jumping
    px = lane_x[player_lane]
    py = player_y
    for o in obstacles:
        if o["meta"].get("gone", False):
            continue
        ox = lane_x[o["lane"]]
        if o["type"].startswith("pick_"):
            if abs(ox - px) > power_pickup_x:
                continue
        else:
            if abs(ox - px) > hit_x:
                continue
        if o["type"] == "train":
            half_len = o["meta"].get("len", train_len_med) * 0.5
        elif o["type"] == "jump":
            half_len = jump_block_l * 0.5
        elif o["type"] == "slide":
            half_len = slide_bar_l * 0.5
        elif o["type"].startswith("pick_"):
            half_len = power_pickup_half_len
        else:
            half_len = 40.0
        if not y_overlap(py, o["y"], half_len):
            continue
        if o["type"].startswith("pick_") and not o["meta"].get("taken", False):
            o["meta"]["taken"] = True
            o["meta"]["gone"] = True
            if o["type"] == "pick_inv":
                start_power(pow_invincible)
            elif o["type"] == "pick_sneakers":
                start_power(pow_sneakers)
            elif o["type"] == "pick_jetpack":
                start_power(pow_jetpack)
            elif o["type"] == "pick_collapse":
                start_power(pow_lane_collapse)
            continue
        if invincible:
            continue
        if sneakers_jump_immunity:
            continue
        if o["type"] == "train":
            if sneakers and (player_bottom_z() >= (train_h - 2.0)):
                continue
            if hoverboard_active:
                o["meta"]["gone"] = True
                break_hoverboard()
                return
            game_over = True
            return
        if o["type"] == "jump":
            if player_bottom_z() <= jump_block_h:
                if hoverboard_active:
                    o["meta"]["gone"] = True
                    break_hoverboard()
                    return
                game_over = True
                return
            continue
        if o["type"] == "slide":
            if not sliding:
                if hoverboard_active:
                    o["meta"]["gone"] = True
                    break_hoverboard()
                    return
                game_over = True
                return
            continue

