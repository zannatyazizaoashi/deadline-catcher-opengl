star_outer_r = 28.0
star_inner_r = 13.0
star_thickness = 14.0
star_scale_min = 0.75
star_scale_max = 1.05

def pulse_scale():
    ms = glutGet(GLUT_ELAPSED_TIME)
    phase = (ms % 900) / 900.0
    tri = 1.0 - abs(2.0 * phase - 1.0)
    smooth = tri * tri * (3.0 - 2.0 * tri)
    return star_scale_min + (star_scale_max - star_scale_min) * smooth

def draw_star_prism(radius_outer, radius_inner, thickness, r, g, b, a):
    pts = [
        (0.0, 1.0), (0.2245, 0.3090),
        (0.9511, 0.3090), (0.3633, -0.1180),
        (0.5878, -0.8090), (0.0, -0.3820),
        (-0.5878, -0.8090), (-0.3633, -0.1180),
        (-0.9511, 0.3090), (-0.2245, 0.3090)
    ]
    front_y = +thickness * 0.5
    back_y = -thickness * 0.5
    glColor4f(r, g, b, a)
    glBegin(GL_TRIANGLES)
    for i in range(10):
        x1, z1 = pts[i]
        x2, z2 = pts[(i + 1) % 10]
        rad1 = radius_outer if (i % 2 == 0) else radius_inner
        rad2 = radius_outer if ((i + 1) % 2 == 0) else radius_inner
        glVertex3f(0.0, front_y, 0.0)
        glVertex3f(x1 * rad1, front_y, z1 * rad1)
        glVertex3f(x2 * rad2, front_y, z2 * rad2)
    glEnd()
    glBegin(GL_TRIANGLES)
    for i in range(10):
        x1, z1 = pts[i]
        x2, z2 = pts[(i + 1) % 10]
        rad1 = radius_outer if (i % 2 == 0) else radius_inner
        rad2 = radius_outer if ((i + 1) % 2 == 0) else radius_inner
        glVertex3f(0.0, back_y, 0.0)
        glVertex3f(x2 * rad2, back_y, z2 * rad2)
        glVertex3f(x1 * rad1, back_y, z1 * rad1)
    glEnd()
    glBegin(GL_QUADS)
    for i in range(10):
        x1, z1 = pts[i]
        x2, z2 = pts[(i + 1) % 10]
        rad1 = radius_outer if (i % 2 == 0) else radius_inner
        rad2 = radius_outer if ((i + 1) % 2 == 0) else radius_inner
        ax, az = x1 * rad1, z1 * rad1
        bx, bz = x2 * rad2, z2 * rad2
        glVertex3f(ax, front_y, az)
        glVertex3f(bx, front_y, bz)
        glVertex3f(bx, back_y, bz)
        glVertex3f(ax, back_y, az)
    glEnd()

