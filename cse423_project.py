def clamp01(x):
    if x < 0.0:
        return 0.0
    if x > 1.0:
        return 1.0
    return x

def lerp(a, b, t):
    return a + (b - a) * t

def night_factor():
    if game_state != state_playing:
        return 0.0
    t = play_cycle_elapsed % day_cycle_period
    if t <= day_to_night_time:
        return clamp01(t / day_to_night_time)
    return clamp01(1.0 - ((t - day_to_night_time) / day_to_night_time))

def env_shade(r, g, b):
    n = night_factor()
    k = 1.0 - 0.55 * n
    a = 0.08 * n
    return clamp01(r * k + a), clamp01(g * k + a), clamp01(b * k + a)

def env_clear_color():
    n = night_factor()
    day = (0.70, 0.88, 1.0)
    night = (0.06, 0.08, 0.16)
    return (lerp(day[0], night[0], n), lerp(day[1], night[1], n), lerp(day[2], night[2], n))

